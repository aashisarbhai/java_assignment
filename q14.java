//Question 14- Write a java program to print alphabets [small case & upper case] on 
//screen [using for loop]? 

public class q14 { 
    public static void main(String[] args) { 
        for(int i = 'a'; i <= 'z'; i++) { 
            System.out.println((char)i); 
        } 
        for(int i = 'A'; i <= 'Z'; i++) { 
            System.out.println((char)i); 
        } 
    } 
} 